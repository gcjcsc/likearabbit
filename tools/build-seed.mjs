// Writes migrations/0002_seed.sql from tools/seed-data.mjs: run `npm run seed` after editing the data
import { writeFileSync } from "node:fs";
import { rabbits } from "./seed-data.mjs";

const FIELDS = ["name", "ear", "sex", "color", "genotype", "weight", "dob", "reg", "gc", "legs", "breeder", "status", "acquired", "notes"];
const sql = (v) => (v == null ? "NULL" : `'${String(v).replaceAll("'", "''")}'`);

// Ids follow list order, so a rabbit's sire or dam can be listed after it
const ids = new Map(rabbits.map((r, i) => [r.key, i + 1]));
const idOf = (key, field, r) => {
  if (!key) return null;
  if (!ids.has(key)) throw new Error(`${r.key}: ${field} "${key}" isn't in the list`);
  return ids.get(key);
};
if (ids.size !== rabbits.length) throw new Error("Two rabbits share a key");

const rows = rabbits.map((r) => {
  const values = FIELDS.map((f) => sql(r[f] ?? (f === "status" ? "ancestor" : "")));
  return `(${ids.get(r.key)}, ${values.join(", ")}, ${idOf(r.sire, "sire", r) ?? "NULL"}, ${idOf(r.dam, "dam", r) ?? "NULL"})`;
});

// Foreign keys are checked at the end of the statement, so forward references are fine
writeFileSync(
  new URL("../migrations/0002_seed.sql", import.meta.url),
  `-- Generated by tools/build-seed.mjs from tools/seed-data.mjs; edit that file, not this one\n` +
    `INSERT INTO rabbits (id, ${FIELDS.join(", ")}, sire_id, dam_id) VALUES\n${rows.join(",\n")};\n`
);
console.log(`Wrote ${rows.length} rabbits`);
